import React, { useState } from 'react';
import { SegmentedControl } from '../cms-ui';
import SectionTypesPanel from './SectionTypesPanel';
import ThresholdsPanel from './ThresholdsPanel';
import CopyEditorPanel from './CopyEditorPanel';
import OverridesPanel from './OverridesPanel';
import AgentPreviewPanel from './AgentPreviewPanel';

const VIEWS = [
  { value: 'sections', label: 'Section types' },
  { value: 'thresholds', label: 'Thresholds' },
  { value: 'copy', label: 'Template copy' },
  { value: 'overrides', label: 'Pins & blocks' },
  { value: 'preview', label: 'Preview as agent' },
];

// Home property sections are generated by the feed engine (PRD: Automated Home Feed v2).
// This tab holds the controls the CMS keeps: switches, guardrails, copy and overrides.
const HomeFeedTab = ({ feed, onToast }) => {
  const [view, setView] = useState('sections');

  return (
    <div className="px-8 space-y-6">
      <SegmentedControl options={VIEWS} value={view} onChange={setView} />

      {view === 'sections' && <SectionTypesPanel sectionTypes={feed.sectionTypes} onToggle={feed.toggleType} />}
      {view === 'thresholds' && (
        <ThresholdsPanel
          key={feed.thresholds.version}
          thresholds={feed.thresholds}
          onSubmit={(values) => { feed.submitThresholds(values); onToast('Thresholds sent for PM approval'); }}
        />
      )}
      {view === 'copy' && (
        <CopyEditorPanel
          sectionTypes={feed.sectionTypes}
          copy={feed.copy}
          onSave={feed.saveCopy}
          onSaved={() => onToast('Template copy saved')}
        />
      )}
      {view === 'overrides' && (
        <OverridesPanel
          sectionTypes={feed.sectionTypes}
          pins={feed.pins}
          blockRules={feed.blockRules}
          onAddPin={feed.addPin}
          onRemovePin={feed.removePin}
          onAddBlockRule={feed.addBlockRule}
          onRemoveBlockRule={feed.removeBlockRule}
        />
      )}
      {view === 'preview' && <AgentPreviewPanel sectionTypes={feed.sectionTypes} />}
    </div>
  );
};

export default HomeFeedTab;
